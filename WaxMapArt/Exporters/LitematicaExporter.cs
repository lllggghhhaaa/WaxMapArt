using System.IO.Compression;
using WaxMapArt.Models;
using WaxNBT;
using WaxNBT.Tags;

namespace WaxMapArt.Exporters;

public class LitematicaExporter : IExporter
{
    public string FileExtension => ".litematic";

    public Stream Export(IReadOnlyList<BlockInfo> blocks, Palette palette)
    {
        var dimensions = CalculateDimensions(blocks);
        var normalized = NormalizePositions(blocks);

        var blockPalette = BuildPalette(normalized);
        var paletteLookup = BuildPaletteLookup(blockPalette);
        var blockStates = PackBlockStates(normalized, dimensions, paletteLookup);
        var paletteTag = BuildBlockStatePalette(blockPalette);

        var metadata = CreateMetadata(dimensions, normalized.Count);
        var region = CreateRegion(dimensions, paletteTag, blockStates);

        var file = new NbtFile();
        file.Root
            .Add(new NbtInt("Version", 7))
            .Add(new NbtInt("MinecraftDataVersion", 3955))
            .Add(metadata)
            .Add(new NbtCompound("Regions").Add(region));

        return Compress(file.SerializeToStream());
    }

    private static (int width, int height, int depth) CalculateDimensions(IReadOnlyList<BlockInfo> blocks)
    {
        if (blocks.Count == 0) return (0, 0, 0);

        var minX = int.MaxValue; var maxX = int.MinValue;
        var minY = int.MaxValue; var maxY = int.MinValue;
        var minZ = int.MaxValue; var maxZ = int.MinValue;

        foreach (var b in blocks)
        {
            if (b.X < minX) minX = b.X;
            if (b.X > maxX) maxX = b.X;
            if (b.Y < minY) minY = b.Y;
            if (b.Y > maxY) maxY = b.Y;
            if (b.Z < minZ) minZ = b.Z;
            if (b.Z > maxZ) maxZ = b.Z;
        }

        return (maxX - minX + 1, maxY - minY + 1, maxZ - minZ + 1);
    }

    private static IReadOnlyList<BlockInfo> NormalizePositions(IReadOnlyList<BlockInfo> blocks)
    {
        if (blocks.Count == 0) return blocks;

        var minX = int.MaxValue; var minY = int.MaxValue; var minZ = int.MaxValue;

        foreach (var b in blocks)
        {
            if (b.X < minX) minX = b.X;
            if (b.Y < minY) minY = b.Y;
            if (b.Z < minZ) minZ = b.Z;
        }

        if (minX == 0 && minY == 0 && minZ == 0) return blocks;

        var normalized = new BlockInfo[blocks.Count];
        for (var i = 0; i < blocks.Count; i++)
        {
            var b = blocks[i];
            normalized[i] = new BlockInfo(b.X - minX, b.Y - minY, b.Z - minZ, b.Id, b.Properties);
        }

        return normalized;
    }

    private static List<(string Id, IReadOnlyDictionary<string, string> Properties)> BuildPalette(
        IReadOnlyList<BlockInfo> blocks)
    {
        var seen = new HashSet<string> { "minecraft:air" };
        var palette = new List<(string, IReadOnlyDictionary<string, string>)>
        {
            ("minecraft:air", new Dictionary<string, string>())
        };

        foreach (var block in blocks)
        {
            var key = block.Properties.Count == 0
                ? block.Id
                : $"{block.Id}[{GetPropsKey(block.Properties)}]";

            if (seen.Add(key))
                palette.Add((block.Id, block.Properties));
        }

        return palette;
    }

    private static Dictionary<(string Id, string PropsKey), int> BuildPaletteLookup(
        List<(string Id, IReadOnlyDictionary<string, string> Properties)> palette)
    {
        var lookup = new Dictionary<(string, string), int>();
        for (var i = 0; i < palette.Count; i++)
            lookup[(palette[i].Id, GetPropsKey(palette[i].Properties))] = i;
        return lookup;
    }

    private static NbtCompound CreateMetadata((int w, int h, int d) dimensions, int totalBlocks)
    {
        var timestamp = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        var volume = dimensions.w * dimensions.h * dimensions.d;

        return new NbtCompound("Metadata")
            .Add(new NbtString("Name", "WaxMapArt"))
            .Add(new NbtString("Description", "Generated by WaxMapArt"))
            .Add(new NbtString("Author", "WaxMapArt"))
            .Add(new NbtCompound("EnclosingSize")
                .Add(new NbtInt("x", dimensions.w))
                .Add(new NbtInt("y", dimensions.h))
                .Add(new NbtInt("z", dimensions.d)))
            .Add(new NbtInt("RegionCount", 1))
            .Add(new NbtLong("TimeCreated", timestamp))
            .Add(new NbtLong("TimeModified", timestamp))
            .Add(new NbtInt("TotalBlocks", totalBlocks))
            .Add(new NbtInt("TotalVolume", volume));
    }

    private static NbtCompound CreateRegion((int w, int h, int d) dimensions,
        NbtList blockStatePalette, long[] blockStates)
    {
        return new NbtCompound("Map")
            .Add(blockStatePalette)
            .Add(new NbtLongArray("BlockStates", blockStates))
            .Add(new NbtList("Entities"))
            .Add(new NbtList("TileEntities"))
            .Add(new NbtList("PendingBlockTicks"))
            .Add(new NbtList("PendingFluidTicks"))
            .Add(new NbtCompound("Position")
                .Add(new NbtInt("x", 0))
                .Add(new NbtInt("y", 0))
                .Add(new NbtInt("z", 0)))
            .Add(new NbtCompound("Size")
                .Add(new NbtInt("x", dimensions.w))
                .Add(new NbtInt("y", dimensions.h))
                .Add(new NbtInt("z", dimensions.d)));
    }

    private static NbtList BuildBlockStatePalette(
        List<(string Id, IReadOnlyDictionary<string, string> Properties)> blockPalette)
    {
        var list = new NbtList("BlockStatePalette");

        foreach (var (id, props) in blockPalette)
        {
            var entry = new NbtCompound()
                .Add(new NbtString("Name", id));

            if (props.Count > 0)
            {
                var propsTag = new NbtCompound("Properties");
                foreach (var (k, v) in props.OrderBy(p => p.Key))
                    propsTag.Add(new NbtString(k, v));
                entry.Add(propsTag);
            }

            list.Add(entry);
        }

        return list;
    }

    private static long[] PackBlockStates(IReadOnlyList<BlockInfo> blocks,
        (int w, int h, int d) dimensions,
        Dictionary<(string Id, string PropsKey), int> paletteLookup)
    {
        var totalBlocks = dimensions.w * dimensions.h * dimensions.d;
        var paletteSize = paletteLookup.Count;
        var bitsPerBlock = Math.Max(2, (int)Math.Ceiling(Math.Log(paletteSize, 2)));
        var mask = (1UL << bitsPerBlock) - 1UL;
        var totalBits = totalBlocks * bitsPerBlock;
        var longCount = (int)Math.Ceiling(totalBits / 64.0);
        var data = new long[longCount];

        var byPos = new Dictionary<(int x, int y, int z), int>(blocks.Count);
        foreach (var b in blocks)
        {
            var stateIndex = paletteLookup[(b.Id, GetPropsKey(b.Properties))];
            byPos[(b.X, b.Y, b.Z)] = stateIndex;
        }

        for (var y = 0; y < dimensions.h; y++)
        for (var z = 0; z < dimensions.d; z++)
        for (var x = 0; x < dimensions.w; x++)
        {
            var blockIndex = (y * dimensions.d + z) * dimensions.w + x;
            var stateIndex = byPos.TryGetValue((x, y, z), out var idx) ? idx : 0;

            var value = (ulong)stateIndex & mask;
            var bitIndex = blockIndex * bitsPerBlock;
            var longIndex = bitIndex / 64;
            var bitOffset = bitIndex % 64;

            data[longIndex] |= (long)(value << bitOffset);

            var remaining = 64 - bitOffset;
            if (remaining < bitsPerBlock)
                data[longIndex + 1] |= (long)(value >> remaining);
        }

        return data;
    }

    private static string GetPropsKey(IReadOnlyDictionary<string, string> props)
    {
        if (props.Count == 0) return string.Empty;
        var keys = props.Keys.OrderBy(k => k).ToArray();
        return string.Join(";", keys.Select(k => $"{k}={props[k]}"));
    }

    private static Stream Compress(Stream rawStream)
    {
        var ms = new MemoryStream();
        using var gzip = new GZipStream(ms, CompressionMode.Compress, true);
        rawStream.CopyTo(gzip);
        rawStream.Close();
        gzip.Flush();
        ms.Seek(0, SeekOrigin.Begin);
        return ms;
    }
}
